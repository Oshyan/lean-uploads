<?php
/** Color policy shared by core-generated sizes and explicit conversions. */
namespace LeanUploads;

defined( 'ABSPATH' ) || exit;

final class Color_Profiles {
	const MAX_PROFILE_BYTES = 4194304;
	private static $contexts = array();

	/** A token is always returned; failed inspection leaves an active, blocking context. */
	public static function push_context( string $source, string $mode = 'preserve' ): int {
		$info = self::inspect( $source );
		$error = is_wp_error( $info ) ? $info : null;
		if ( ! in_array( $mode, array( 'preserve', 'srgb' ), true ) ) {
			$error = new \WP_Error( 'lean_uploads_color_mode', 'Unknown color policy.' );
		}
		if ( ! $error && ! empty( $info['has_icc'] ) && ! class_exists( '\Imagick' ) ) {
			$error = new \WP_Error( 'lean_uploads_color_editor', 'This image has a color profile and needs Imagick to preserve its colors safely.' );
		}
		$token = count( self::$contexts );
		self::$contexts[] = array( 'source' => $info, 'mode' => $mode, 'error' => $error );
		return $token;
	}

	public static function pop_context( int $token ): void {
		$error = self::context_error();
		self::$contexts = array_slice( self::$contexts, 0, max( 0, $token ) );
		if ( $error && self::$contexts ) { self::fail( $error ); }
	}

	public static function expected_profile(): string {
		$c = self::context();
		if ( ! $c || $c['error'] || empty( $c['source']['has_icc'] ) ) { return ''; }
		if ( 'srgb' === $c['mode'] && ! $c['source']['is_srgb'] ) {
			$profile = self::srgb_profile();
			return is_wp_error( $profile ) ? '' : $profile;
		}
		return $c['source']['icc'];
	}

	public static function context_error() {
		$c = self::context();
		return $c ? $c['error'] : null;
	}

	private static function context(): ?array {
		return self::$contexts ? self::$contexts[ count( self::$contexts ) - 1 ] : null;
	}

	/** Save failures must reach the finalizer: core may otherwise silently omit failed sizes. */
	public static function fail( \WP_Error $error ): \WP_Error {
		if ( self::$contexts ) {
			self::$contexts[ count( self::$contexts ) - 1 ]['error'] = $error;
		}
		return $error;
	}

	/** Restrict profiled work to an editor whose saved outputs are checked; untagged work stays cooperative. */
	public static function filter_editors( $editors ): array {
		$c = self::context();
		if ( ! $c ) { return (array) $editors; }
		if ( $c['error'] ) { return array(); }
		if ( empty( $c['source']['has_icc'] ) ) { return (array) $editors; }
		if ( ! class_exists( '\WP_Image_Editor_Imagick', false ) ) {
			require_once ABSPATH . WPINC . '/class-wp-image-editor.php';
			require_once ABSPATH . WPINC . '/class-wp-image-editor-imagick.php';
		}
		if ( ! class_exists( __NAMESPACE__ . '\Color_Editor_Imagick', false ) ) {
			require_once __DIR__ . '/class-color-editor-imagick.php';
		}
		return array( __NAMESPACE__ . '\Color_Editor_Imagick' );
	}

	/** The bundled generic profile is generated by LittleCMS, not copied from a device or operating system. */
	public static function srgb_profile() {
		$profile = @file_get_contents( dirname( __DIR__ ) . '/assets/srgb.icc' );
		if ( ! is_string( $profile ) || ! self::valid_icc( $profile ) ) {
			return new \WP_Error( 'lean_uploads_srgb_profile', 'The standard sRGB profile is unavailable or invalid.' );
		}
		return $profile;
	}

	public static function valid_icc( string $profile ): bool {
		if ( strlen( $profile ) < 132 || strlen( $profile ) > self::MAX_PROFILE_BYTES || 'acsp' !== substr( $profile, 36, 4 ) ) { return false; }
		$size = unpack( 'N', substr( $profile, 0, 4 ) )[1];
		$count = unpack( 'N', substr( $profile, 128, 4 ) )[1];
		if ( $size !== strlen( $profile ) || $count > 4096 || 132 + 12 * $count > $size ) { return false; }
		for ( $i = 0; $i < $count; ++$i ) {
			$entry = unpack( 'Noffset/Nsize', substr( $profile, 136 + 12 * $i, 8 ) );
			if ( $entry['offset'] < 132 + 12 * $count || $entry['size'] < 8 || $entry['offset'] + $entry['size'] > $size ) { return false; }
		}
		return true;
	}

	/** Conservative matrix-shaper equivalence; profile names and descriptions are never evidence of sRGB. */
	public static function is_srgb_profile( string $profile ): bool {
		$target = self::srgb_profile();
		if ( is_wp_error( $target ) || ! self::valid_icc( $profile ) ) { return false; }
		if ( hash_equals( hash( 'sha256', $target ), hash( 'sha256', $profile ) ) ) { return true; }
		if ( 'RGB ' !== substr( $profile, 16, 4 ) || substr( $profile, 20, 4 ) !== substr( $target, 20, 4 ) ) { return false; }
		$tags = static function ( $data ) {
			$result = array();
			$count = unpack( 'N', substr( $data, 128, 4 ) )[1];
			for ( $i = 0; $i < $count; ++$i ) {
				$name = substr( $data, 132 + 12 * $i, 4 );
				$entry = unpack( 'Noffset/Nsize', substr( $data, 136 + 12 * $i, 8 ) );
				if ( isset( $result[ $name ] ) ) { return array(); }
				$result[ $name ] = substr( $data, $entry['offset'], $entry['size'] );
			}
			return $result;
		};
		$a = $tags( $profile ); $b = $tags( $target );
		foreach ( array_keys( $a ) as $name ) {
			if ( preg_match( '/^(A2B|B2A|D2B|B2D)/', $name ) ) { return false; }
		}
		foreach ( array( 'rXYZ', 'gXYZ', 'bXYZ' ) as $name ) {
			if ( ! isset( $a[ $name ], $b[ $name ] ) || 'XYZ ' !== substr( $a[ $name ], 0, 4 ) || strlen( $a[ $name ] ) < 20 ) { return false; }
			for ( $i = 0; $i < 3; ++$i ) {
				if ( abs( self::fixed( $a[ $name ], 8 + 4 * $i ) - self::fixed( $b[ $name ], 8 + 4 * $i ) ) > 0.0003 ) { return false; }
			}
		}
		if ( ! isset( $a['wtpt'] ) || strlen( $a['wtpt'] ) < 20 || 'XYZ ' !== substr( $a['wtpt'], 0, 4 ) ) { return false; }
		$whitepoints = array( array( 0.9642, 1.0, 0.8249 ) );
		// Legacy v2 monitor profiles may retain D65 media white while their RGB colorants are D50-adapted.
		if ( 2 === ord( $profile[8] ) && 'mntr' === substr( $profile, 12, 4 ) && ! isset( $a['chad'] ) ) {
			$whitepoints[] = array( 0.95047, 1.0, 1.08883 );
		}
		$white_matches = false;
		foreach ( $whitepoints as $white ) {
			$match = true;
			for ( $i = 0; $i < 3; ++$i ) { $match = $match && abs( self::fixed( $a['wtpt'], 8 + 4 * $i ) - $white[ $i ] ) <= 0.0003; }
			$white_matches = $white_matches || $match;
		}
		if ( ! $white_matches ) { return false; }
		foreach ( array( 'rTRC', 'gTRC', 'bTRC' ) as $name ) {
			if ( ! isset( $a[ $name ], $b[ $name ] ) ) { return false; }
			for ( $i = 0; $i <= 256; ++$i ) {
				$x = self::curve( $a[ $name ], $i / 256 ); $y = self::curve( $b[ $name ], $i / 256 );
				if ( null === $x || null === $y || ! is_finite( $x ) || abs( $x - $y ) > 0.0005 ) { return false; }
			}
		}
		return true;
	}

	private static function fixed( string $data, int $offset ): float {
		$v = unpack( 'N', substr( $data, $offset, 4 ) )[1];
		return ( $v >= 2147483648 ? $v - 4294967296 : $v ) / 65536;
	}

	/** Decode ICC v2 sampled/gamma curves and v4 parametric curves into linear light. */
	private static function curve( string $data, float $x ): ?float {
		if ( strlen( $data ) < 12 ) { return null; }
		$type = substr( $data, 0, 4 );
		if ( 'curv' === $type ) {
			$n = unpack( 'N', substr( $data, 8, 4 ) )[1];
			if ( 12 + 2 * $n > strlen( $data ) ) { return null; }
			if ( 0 === $n ) { return $x; }
			if ( 1 === $n ) { return pow( $x, unpack( 'n', substr( $data, 12, 2 ) )[1] / 256 ); }
			$position = $x * ( $n - 1 ); $left = (int) floor( $position ); $right = min( $n - 1, $left + 1 );
			$a = unpack( 'n', substr( $data, 12 + 2 * $left, 2 ) )[1] / 65535;
			$b = unpack( 'n', substr( $data, 12 + 2 * $right, 2 ) )[1] / 65535;
			return $a + ( $b - $a ) * ( $position - $left );
		}
		if ( 'para' !== $type ) { return null; }
		$f = unpack( 'n', substr( $data, 8, 2 ) )[1]; $counts = array( 1, 3, 4, 5, 7 );
		if ( ! isset( $counts[ $f ] ) || strlen( $data ) < 12 + 4 * $counts[ $f ] ) { return null; }
		$p = array();
		for ( $i = 0; $i < $counts[ $f ]; ++$i ) { $p[] = self::fixed( $data, 12 + 4 * $i ); }
		if ( 0 === $f ) { return pow( $x, $p[0] ); }
		if ( 0.0 === $p[1] ) { return null; }
		if ( 1 === $f ) { return $x >= -$p[2] / $p[1] ? pow( max( 0, $p[1] * $x + $p[2] ), $p[0] ) : 0.0; }
		if ( 2 === $f ) { return ( $x >= -$p[2] / $p[1] ? pow( max( 0, $p[1] * $x + $p[2] ), $p[0] ) : 0.0 ) + $p[3]; }
		if ( 3 === $f ) { return $x >= $p[4] ? pow( max( 0, $p[1] * $x + $p[2] ), $p[0] ) : $p[3] * $x; }
		return $x >= $p[4] ? pow( max( 0, $p[1] * $x + $p[2] ), $p[0] ) + $p[5] : $p[3] * $x + $p[6];
	}

	/** Header inspection does not require GD to decode pixels or silently discard ICC. */
	public static function inspect( string $path ) {
		if ( ! is_file( $path ) || ! is_readable( $path ) ) { return new \WP_Error( 'lean_uploads_color_read', 'Cannot inspect image color information.' ); }
		$fh = @fopen( $path, 'rb' );
		if ( ! $fh ) { return new \WP_Error( 'lean_uploads_color_read', 'Cannot open image for color inspection.' ); }
		try {
			$head = fread( $fh, 12 );
			$profile = ''; $mime = ''; $nonstandard_png_color = false;
			if ( "\x89PNG\r\n\x1a\n" === substr( $head, 0, 8 ) ) {
				$mime = 'image/png'; fseek( $fh, 8 );
				for ( $i = 0; $i < 100000; ++$i ) {
					$h = self::read_exact( $fh, 8 ); $n = unpack( 'N', substr( $h, 0, 4 ) )[1]; $type = substr( $h, 4, 4 );
					if ( 'iCCP' === $type ) {
						if ( $profile || $n > self::MAX_PROFILE_BYTES ) { throw new \RuntimeException( 'Invalid or oversized PNG color profile.' ); }
						$data = self::read_exact( $fh, $n ); $zero = strpos( $data, "\0" );
						if ( false === $zero || $zero > 79 || ! isset( $data[ $zero + 1 ] ) || "\0" !== $data[ $zero + 1 ] ) { throw new \RuntimeException( 'Invalid PNG color profile.' ); }
						$profile = @gzuncompress( substr( $data, $zero + 2 ), self::MAX_PROFILE_BYTES );
						if ( ! is_string( $profile ) || '' === $profile ) { throw new \RuntimeException( 'Cannot read compressed PNG color profile.' ); }
					} elseif ( 'acTL' === $type ) {
						throw new \RuntimeException( 'Animated PNG images are not processed by the color pipeline.' );
					} elseif ( 'gAMA' === $type ) {
						if ( 4 !== $n ) { throw new \RuntimeException( 'Invalid PNG gamma declaration.' ); }
						$gamma = unpack( 'N', self::read_exact( $fh, 4 ) )[1];
						$nonstandard_png_color = $nonstandard_png_color || abs( $gamma - 45455 ) > 5;
					} elseif ( 'cHRM' === $type ) {
						if ( 32 !== $n ) { throw new \RuntimeException( 'Invalid PNG chromaticity declaration.' ); }
						$chroma = array_values( unpack( 'N8', self::read_exact( $fh, 32 ) ) );
						foreach ( array( 31270, 32900, 64000, 33000, 30000, 60000, 15000, 6000 ) as $key => $value ) {
							$nonstandard_png_color = $nonstandard_png_color || abs( $chroma[ $key ] - $value ) > 5;
						}
					} elseif ( 'cICP' === $type ) {
						$nonstandard_png_color = true; self::skip( $fh, $n );
					} else { self::skip( $fh, $n ); }
					self::read_exact( $fh, 4 );
					if ( 'IEND' === $type ) { break; }
				}
				if ( 'IEND' !== $type ) { throw new \RuntimeException( 'PNG metadata inspection limit reached.' ); }
			} elseif ( "\xff\xd8" === substr( $head, 0, 2 ) ) {
				$mime = 'image/jpeg'; fseek( $fh, 2 ); $parts = array(); $total = 0;
				for ( $i = 0; $i < 100000; ++$i ) {
					if ( "\xff" !== self::read_exact( $fh, 1 ) ) { throw new \RuntimeException( 'Invalid JPEG marker.' ); }
					do { $marker = ord( self::read_exact( $fh, 1 ) ); } while ( 255 === $marker );
					if ( 218 === $marker || 217 === $marker ) { break; }
					if ( 1 === $marker || ( $marker >= 208 && $marker <= 215 ) ) { continue; }
					$n = unpack( 'n', self::read_exact( $fh, 2 ) )[1] - 2;
					if ( $n < 0 ) { throw new \RuntimeException( 'Invalid JPEG segment.' ); }
					if ( 226 !== $marker ) { self::skip( $fh, $n ); continue; }
					$data = self::read_exact( $fh, $n );
					if ( "ICC_PROFILE\0" !== substr( $data, 0, 12 ) ) { continue; }
					if ( strlen( $data ) < 14 ) { throw new \RuntimeException( 'Incomplete JPEG profile.' ); }
					$part = ord( $data[12] ); $count = ord( $data[13] );
					if ( ! $part || $part > $count || isset( $parts[ $part ] ) || ( $total && $count !== $total ) ) { throw new \RuntimeException( 'Invalid JPEG profile sequence.' ); }
					$total = $count; $parts[ $part ] = substr( $data, 14 );
					if ( array_sum( array_map( 'strlen', $parts ) ) > self::MAX_PROFILE_BYTES ) { throw new \RuntimeException( 'Oversized JPEG color profile.' ); }
				}
				if ( 218 !== $marker && 217 !== $marker ) { throw new \RuntimeException( 'JPEG metadata inspection limit reached.' ); }
				if ( count( $parts ) !== $total ) { throw new \RuntimeException( 'Incomplete JPEG color profile.' ); }
				ksort( $parts ); $profile = implode( '', $parts );
			} elseif ( 'RIFF' === substr( $head, 0, 4 ) && 'WEBP' === substr( $head, 8, 4 ) ) {
				$mime = 'image/webp'; $limit = unpack( 'V', substr( $head, 4, 4 ) )[1] + 8; $flag = false;
				while ( ftell( $fh ) + 8 <= $limit ) {
					$h = self::read_exact( $fh, 8 ); $type = substr( $h, 0, 4 ); $n = unpack( 'V', substr( $h, 4, 4 ) )[1];
					if ( $n > $limit - ftell( $fh ) ) { throw new \RuntimeException( 'Invalid WebP chunk.' ); }
					if ( in_array( $type, array( 'ANIM', 'ANMF' ), true ) ) { throw new \RuntimeException( 'Animated WebP images are not processed by the color pipeline.' ); }
					if ( 'ICCP' === $type ) {
						if ( $profile || $n > self::MAX_PROFILE_BYTES ) { throw new \RuntimeException( 'Invalid WebP color profile.' ); }
						$profile = self::read_exact( $fh, $n );
					} elseif ( 'VP8X' === $type && $n > 0 ) {
						$flag = (bool) ( ord( self::read_exact( $fh, 1 ) ) & 32 ); self::skip( $fh, $n - 1 );
					} else { self::skip( $fh, $n ); }
					if ( $n % 2 ) { self::read_exact( $fh, 1 ); }
				}
				if ( $flag && '' === $profile ) { throw new \RuntimeException( 'WebP declares a missing color profile.' ); }
			} else {
				if ( ! class_exists( '\Imagick' ) ) { throw new \RuntimeException( 'This format needs Imagick for safe color-profile inspection.' ); }
				$im = new \Imagick();
				try {
					$im->pingImage( $path );
					if ( 1 !== $im->getNumberImages() ) { throw new \RuntimeException( 'Animated or multi-frame images are not processed by the color pipeline.' ); }
					$profile = self::image_profile( $im ); $mime = $im->getImageMimeType();
				}
				finally { $im->clear(); }
			}
			if ( '' === $profile && $nonstandard_png_color ) { throw new \RuntimeException( 'This PNG has nonstandard color declarations without an ICC profile; preserving its appearance requires a color-managed source export.' ); }
			if ( '' !== $profile && ! self::valid_icc( $profile ) ) { throw new \RuntimeException( 'Image contains an invalid ICC profile.' ); }
			return array( 'has_icc' => '' !== $profile, 'icc' => $profile, 'hash' => '' === $profile ? '' : hash( 'sha256', $profile ), 'is_srgb' => '' !== $profile && self::is_srgb_profile( $profile ), 'mime' => $mime );
		} catch ( \Throwable $e ) {
			return new \WP_Error( 'lean_uploads_color_inspect', $e->getMessage() );
		} finally { fclose( $fh ); }
	}

	private static function read_exact( $fh, int $length ): string {
		if ( $length < 0 || $length > self::MAX_PROFILE_BYTES ) { throw new \RuntimeException( 'Image metadata exceeds the inspection limit.' ); }
		if ( 0 === $length ) { return ''; }
		$data = fread( $fh, $length );
		if ( ! is_string( $data ) || strlen( $data ) !== $length ) { throw new \RuntimeException( 'Truncated image metadata.' ); }
		return $data;
	}

	private static function skip( $fh, int $length ): void {
		$stat = fstat( $fh );
		if ( $length < 0 || ftell( $fh ) + $length > $stat['size'] || 0 !== fseek( $fh, $length, SEEK_CUR ) ) { throw new \RuntimeException( 'Truncated image data.' ); }
	}

	public static function image_profile( \Imagick $im ): string {
		$profiles = $im->getImageProfiles( '*', true );
		return (string) ( $profiles['icc'] ?? $profiles['icm'] ?? '' );
	}

	/** Prepare pixels once, before resizing. Returns the profile that must survive every saved output. */
	public static function prepare_image( \Imagick $im, ?string $mode = null ) {
		$c = self::context();
		if ( $c && $c['error'] ) { return $c['error']; }
		$mode = $mode ?? ( $c['mode'] ?? 'preserve' );
		try {
			if ( 1 !== $im->getNumberImages() ) { throw new \RuntimeException( 'Animated or multi-frame images are not processed by the color pipeline.' ); }
			$profile = self::image_profile( $im );
			if ( '' === $profile ) {
				if ( $c && ! empty( $c['source']['has_icc'] ) ) { throw new \RuntimeException( 'The decoder discarded the source color profile.' ); }
				return ''; // Untagged files remain untagged; never invent their source color space.
			}
			if ( ! self::valid_icc( $profile ) ) { throw new \RuntimeException( 'The image color profile is invalid.' ); }
			// Indexed PNG bit depth describes palette indices, not its 8-bit RGB entries. Core reapplies
			// getImageDepth() after resizing, which otherwise rounds palette colors down to 1/2/4-bit RGB.
			if ( 'PNG' === strtoupper( $im->getImageFormat() ) && '3' === $im->getImageProperty( 'png:IHDR.color-type-orig' ) && $im->getImageDepth() < 8 ) {
				$im->setImageDepth( 8 );
			}
			if ( 'srgb' === $mode && ! self::is_srgb_profile( $profile ) ) {
				$target = self::srgb_profile();
				if ( is_wp_error( $target ) ) { return self::fail( $target ); }
				$delegates = implode( ' ', \Imagick::getConfigureOptions( 'DELEGATES' ) );
				if ( false === stripos( $delegates, 'lcms' ) ) { throw new \RuntimeException( 'True sRGB conversion needs ImageMagick with LittleCMS support.' ); }
				if ( ! $im->profileImage( 'icc', $target ) ) { throw new \RuntimeException( 'The color-managed sRGB transform failed.' ); }
				$profile = self::image_profile( $im );
				if ( ! hash_equals( hash( 'sha256', $target ), hash( 'sha256', $profile ) ) ) { throw new \RuntimeException( 'The sRGB transform did not install its target profile.' ); }
			} elseif ( 'RGB ' !== substr( $profile, 16, 4 ) ) {
				throw new \RuntimeException( 'This non-RGB profile needs explicit sRGB normalization before conversion.' );
			}
			return $profile;
		} catch ( \Throwable $e ) { return self::fail( new \WP_Error( 'lean_uploads_color_transform', $e->getMessage() ) ); }
	}

	/** WordPress excludes PNG ancillary chunks after resizing; undo that for a tagged saved image. */
	public static function prepare_save( \Imagick $im, string $profile ): void {
		if ( '' === $profile ) { return; }
		// Core uses a wand option; stripImage() also installs a per-image artifact. Both can suppress iCCP.
		$im->setOption( 'png:exclude-chunk', '' );
		$im->setImageArtifact( 'png:exclude-chunk', '' );
		$include = array_filter( array_map( 'trim', explode( ',', (string) $im->getOption( 'png:include-chunk' ) ) ) );
		$include[] = 'iCCP';
		$include = implode( ',', array_unique( $include ) );
		$im->setOption( 'png:include-chunk', $include );
		$im->setImageArtifact( 'png:include-chunk', $include );
	}

	public static function validate_file( string $path, string $expected ) {
		if ( '' === $expected ) { return true; }
		$info = self::inspect( $path );
		if ( is_wp_error( $info ) ) { return self::fail( $info ); }
		if ( ! $info['has_icc'] || ! hash_equals( hash( 'sha256', $expected ), $info['hash'] ) ) {
			return self::fail( new \WP_Error( 'lean_uploads_color_output', 'The saved image lost or changed its required color profile; the original must be retained.' ) );
		}
		return true;
	}

	/** Explicit same-format normalization for staged files. Never overwrite the source or auto-rotate pixels. */
	public static function normalize_file( string $source, string $dest ) {
		if ( $source === $dest || ( realpath( $source ) && realpath( $source ) === realpath( $dest ) ) ) { return new \WP_Error( 'lean_uploads_color_destination', 'Normalize into a separate staged file.' ); }
		$token = self::push_context( $source, 'srgb' ); $im = null;
		try {
			if ( self::context_error() ) { return self::context_error(); }
			$c = self::context();
			if ( empty( $c['source']['has_icc'] ) ) { return new \WP_Error( 'lean_uploads_color_untagged', 'Cannot normalize an image with no source ICC profile.' ); }
			$size = wp_getimagesize( $source );
			$max_pixels = (int) apply_filters( 'lean_uploads_max_pixels', 120000000 );
			if ( ! $size || ( $max_pixels > 0 && (float) $size[0] * $size[1] > $max_pixels ) ) {
				return new \WP_Error( 'lean_uploads_color_pixels', 'Image dimensions exceed the safe color-normalization limit.' );
			}
			$im = new \Imagick( $source );
			if ( 1 !== $im->getNumberImages() ) { return new \WP_Error( 'lean_uploads_color_frames', 'Animated or multi-frame images are not normalized.' ); }
			$expected = self::prepare_image( $im, 'srgb' );
			if ( is_wp_error( $expected ) ) { return $expected; }
			$format = strtoupper( $im->getImageFormat() ); $width = $im->getImageWidth(); $height = $im->getImageHeight();
			if ( ! in_array( $format, array( 'PNG', 'JPEG', 'JPG', 'WEBP', 'AVIF' ), true ) ) { return new \WP_Error( 'lean_uploads_color_format', 'This format is not supported for same-format normalization.' ); }
			if ( 'WEBP' === $format ) { $im->setOption( 'webp:lossless', 'true' ); $im->setImageCompressionQuality( 100 ); }
			elseif ( in_array( $format, array( 'JPEG', 'JPG', 'AVIF' ), true ) ) { $im->setImageCompressionQuality( 100 ); }
			self::prepare_save( $im, $expected );
			if ( ! $im->writeImage( $dest ) ) { return new \WP_Error( 'lean_uploads_color_write', 'Could not write normalized output.' ); }
			$checked = self::validate_file( $dest, $expected );
			if ( is_wp_error( $checked ) ) { return $checked; }
			$probe = new \Imagick();
			try {
				$probe->pingImage( $dest );
				if ( $probe->getImageWidth() !== $width || $probe->getImageHeight() !== $height || $probe->getImageMimeType() !== $im->getImageMimeType() ) {
					return new \WP_Error( 'lean_uploads_color_geometry', 'Normalized output changed format or dimensions.' );
				}
			} finally { $probe->clear(); }
			return true;
		} catch ( \Throwable $e ) { return new \WP_Error( 'lean_uploads_color_normalize', $e->getMessage() ); }
		finally { if ( $im ) { $im->clear(); } self::pop_context( $token ); }
	}
}
